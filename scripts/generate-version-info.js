#!/usr/bin/env node
/**
 * Generate version info from git at build time.
 *
 * Writes src/version-info.ts with current git commit hash, branch,
 * and version from manifest.json. This lets the plugin display
 * exact build metadata in Settings without runtime git access.
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const OUTPUT = path.join(ROOT, "src", "version-info.ts");

function getGitInfo() {
	try {
		const commitHash = execSync("git rev-parse HEAD", {
			encoding: "utf-8",
			cwd: ROOT,
		}).trim();
		const branchName = execSync("git rev-parse --abbrev-ref HEAD", {
			encoding: "utf-8",
			cwd: ROOT,
		}).trim();
		return { commitHash, branchName };
	} catch (err) {
		console.warn("[version-info] Could not get git info:", err.message);
		return { commitHash: "unknown", branchName: "unknown" };
	}
}

function getManifestVersion() {
	try {
		const manifestPath = path.join(ROOT, "manifest.json");
		const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
		return manifest.version || "0.0.0";
	} catch (err) {
		console.warn("[version-info] Could not read manifest:", err.message);
		return "0.0.0";
	}
}

function generate() {
	const { commitHash, branchName } = getGitInfo();
	const version = getManifestVersion();
	const shortHash =
		commitHash === "unknown" ? "unknown" : commitHash.slice(0, 7);
	const buildTime = new Date().toISOString();

	const content = `// AUTO-GENERATED by scripts/generate-version-info.js
// Do not edit manually — run 'pnpm run build' or 'node scripts/generate-version-info.js' to regenerate.

export const PLUGIN_VERSION = "${version}";
export const GIT_COMMIT_HASH = "${commitHash}";
export const GIT_SHORT_HASH = "${shortHash}";
export const GIT_BRANCH = "${branchName}";
export const BUILD_TIME = "${buildTime}";
`;

	fs.writeFileSync(OUTPUT, content);
	console.log(
		`[version-info] Generated: version=${version} branch=${branchName} commit=${shortHash}`,
	);
}

generate();
